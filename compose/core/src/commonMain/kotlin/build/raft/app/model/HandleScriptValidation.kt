/**
 * One script per handle: UTS #39 "Highly Restrictive" (section 5.2), parity with
 * `botiverse/slock` `packages/shared/src/handleScript.ts` (#17270).
 *
 * Generated from Unicode 17.0.0 `Scripts.txt` (SHA-256
 * `9f5e50d3abaee7d6ce09480f325c706f485ae3240912527e651954d2d6b035bf`),
 * `ScriptExtensions.txt` (SHA-256
 * `ec2107e58825a1586acee8e0911ce18260394ac8b87e535ca325f1ccbeb06bc6`), and
 * `PropertyValueAliases.txt` (SHA-256
 * `64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a`).
 */
fun isSingleScriptHandle(handle: String): Boolean {
    var resolved: MutableSet<Int>? = null
    var index = 0
    while (index < handle.length) {
        val first = handle[index]
        val codePoint: Int
        if (first.isHighSurrogate() && index + 1 < handle.length && handle[index + 1].isLowSurrogate()) {
            codePoint = 0x10000 + ((first.code - 0xD800) shl 10) + (handle[index + 1].code - 0xDC00)
            index += 2
        } else {
            codePoint = first.code
            index += 1
        }
        val keyId = lookupHandleScriptKey(codePoint)
        if (keyId == HANDLE_SCRIPT_NEUTRAL_KEY) continue
        val scripts: IntArray = if (keyId > 0) HANDLE_SCRIPT_AUGMENTED_SETS[keyId] else intArrayOf(-(codePoint + 1))
        if (resolved == null) {
            resolved = HashSet<Int>(scripts.size * 2).apply { for (s in scripts) add(s) }
        } else {
            val iter = resolved.iterator()
            while (iter.hasNext()) {
                val candidate = iter.next()
                var matched = false
                for (s in scripts) {
                    if (s == candidate) {
                        matched = true
                        break
                    }
                }
                if (!matched) iter.remove()
            }
        }
        if (resolved.isEmpty()) return false
    }
    return true
}

private const val HANDLE_SCRIPT_NEUTRAL_KEY = 0
private const val HANDLE_SCRIPT_RANGE_WIDTH = 15

private fun lookupHandleScriptKey(codePoint: Int): Int {
    val table = HANDLE_SCRIPT_RANGES
    var low = 0
    var high = table.length / HANDLE_SCRIPT_RANGE_WIDTH - 1
    while (low <= high) {
        val mid = (low + high) ushr 1
        val offset = mid * HANDLE_SCRIPT_RANGE_WIDTH
        val start = table.hexAt(offset, 6)
        val end = table.hexAt(offset + 6, 6)
        when {
            codePoint < start -> high = mid - 1
            codePoint > end -> low = mid + 1
            else -> return table.hexAt(offset + 12, 3)
        }
    }
    return -1
}

private fun String.hexAt(offset: Int, width: Int): Int {
    var value = 0
    for (i in 0 until width) {
        val ch = this[offset + i]
        val digit = when (ch) {
            in '0'..'9' -> ch.code - '0'.code
            in 'A'..'F' -> ch.code - 'A'.code + 10
            else -> error("Invalid hex in generated handle script table")
        }
        value = (value shl 4) or digit
    }
    return value
}


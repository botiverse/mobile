import { hapTasks } from '@ohos/hvigor-ohos-plugin';
import { kuiklyCompilePlugin } from '../hvigor/kuiklyPlugin';
import { slockOhosOAuthCallbackPlugin } from '../hvigor/oauthCallbackPlugin';
import { execFileSync } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';

syncSlockFontRawfiles();
writeSlockOhosBuildMetadata();

export default {
    system: hapTasks,  /* Built-in plugin of Hvigor. It cannot be modified. */
    plugins:[slockOhosOAuthCallbackPlugin(), kuiklyCompilePlugin()] /* Custom plugins. */
}

function syncSlockFontRawfiles(): void {
    const sourceDir = path.resolve(__dirname, 'src/main/resources/resfile/fonts');
    const rawfileDir = path.resolve(__dirname, 'src/main/resources/rawfile/fonts');

    if (!fs.existsSync(sourceDir)) {
        return;
    }

    fs.mkdirSync(rawfileDir, { recursive: true });
    fs.readdirSync(sourceDir)
        .filter((fileName: string) => fileName.endsWith('.ttf'))
        .forEach((fileName: string) => {
            fs.copyFileSync(
                path.join(sourceDir, fileName),
                path.join(rawfileDir, fileName),
            );
        });
}

function writeSlockOhosBuildMetadata(): void {
    const generatedDir = path.resolve(__dirname, 'src/main/ets/kuikly/generated');
    const outputPath = path.join(generatedDir, 'SlockOhosBuildMetadata.ets');
    const gitCommit = slockGitCommit();
    const buildTime = new Date().toISOString();

    fs.mkdirSync(generatedDir, { recursive: true });
    fs.writeFileSync(
        outputPath,
        [
            '// Generated by entry/hvigorfile.ts. Do not edit by hand.',
            `export const SLOCK_OHOS_BUILD_TIME = '${escapeArkTsString(buildTime)}';`,
            `export const SLOCK_OHOS_GIT_COMMIT = '${escapeArkTsString(gitCommit)}';`,
            ''
        ].join('\n')
    );
}

function slockGitCommit(): string {
    try {
        return execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
            cwd: path.resolve(__dirname, '../../'),
            encoding: 'utf8'
        }).trim() || 'unknown';
    } catch (_error) {
        return process.env.SLOCK_GIT_COMMIT ?? process.env.GITHUB_SHA?.slice(0, 12) ?? 'unknown';
    }
}

function escapeArkTsString(value: string): string {
    return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

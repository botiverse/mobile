/**
 * Runtime marks, as web `RackRuntimeMark` (botiverse/slock `packages/web/src/components/machine/rack/
 * RackRuntimeUsage.tsx`): each mark is drawn as one shape in the text's colour (web draws the SVG
 * as a CSS mask over `currentColor`), so a multi-colour mark is its silhouette here too.
 *
 * Paths: `@botiverse/oar` 0.76.3 `assets/brands/*.svg` (LobeHub lobe-icons, MIT; Pi from pi.dev;
 * see that package's `assets/brands/NOTICE.md`). Brand names and marks belong to their owners.
 * Antigravity is its mask shape (the coloured fills inside it are not drawn). Path data is
 * normalized (explicit commands and separators) from the upstream SVG; geometry is unchanged.
 */
internal data class RaftRuntimeMarkPath(val pathData: String, val evenOdd: Boolean)

internal data class RaftRuntimeMarkSpec(
    val viewportWidth: Float,
    val viewportHeight: Float,
    val paths: List<RaftRuntimeMarkPath>,
)

internal object RaftRuntimeMarks {
    // Composition runs on the main thread; the cache is only touched from there and from tests.
    private val cache = HashMap<String, ImageVector>()

    /** The mark's runtime for [runtimeId] (web `RUNTIME_MARKS`), or null for a runtime with none. */
    fun markId(runtimeId: String): String? =
        when (runtimeId.trim()) {
            "claude" -> "claude"
            "codex" -> "codex"
            "grok" -> "grok"
            "builtin", "pi" -> "pi"
            "antigravity" -> "antigravity"
            "kimi", "kimi-sdk" -> "kimi"
            "cursor" -> "cursor"
            "opencode" -> "opencode"
            "qwen" -> "qwen"
            "qoder" -> "qoder"
            else -> null
        }

    fun spec(runtimeId: String): RaftRuntimeMarkSpec? = markId(runtimeId)?.let { SPECS[it] }

    /** The mark as an opaque black vector, tinted at draw time; null for a runtime with none. */
    fun vector(runtimeId: String): ImageVector? {
        val id = markId(runtimeId) ?: return null
        val spec = SPECS[id] ?: return null
        return cache.getOrPut(id) {
            ImageVector.Builder(
                name = "runtime-mark-$id",
                defaultWidth = 12.dp,
                defaultHeight = 12.dp,
                viewportWidth = spec.viewportWidth,
                viewportHeight = spec.viewportHeight,
            ).apply {
                spec.paths.forEach { path ->
                    addPath(
                        pathData = addPathNodes(path.pathData),
                        pathFillType = if (path.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                        fill = SolidColor(Color.Black), // raft-color: mask shape, tinted at draw time
                    )
                }
            }.build()
        }
    }


/**
 * A runtime's mark, [size] square, in [color]; web shows lucide
 * `SquareTerminal` for a runtime with no mark, and so does this.
 */
@Composable
internal fun RaftRuntimeMark(runtimeId: String, color: Color, size: Dp = 12.dp) {
    val vector = RaftRuntimeMarks.vector(runtimeId)
    if (vector == null) {
        CompositionLocalProvider(LocalRaftContentColor provides color) {
            RaftComputersIcon(RaftLucideIconName.SquareTerminal, size = size)
        }
        return
    }
    Image(
        painter = rememberVectorPainter(vector),
        contentDescription = null,
        modifier = Modifier.size(size),
        colorFilter = ColorFilter.tint(color),
    )
}

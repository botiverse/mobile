@Composable
private fun bottomSafeAreaPadding(): Float {
    val pageData = (LocalActivity.current.getPager() as Pager).pageData
    val safeBottom = pageData.safeAreaInsets.bottom
    val androidBottom = pageData.androidBottomBavBarHeight
    return safeBottom.coerceAtLeast(androidBottom).coerceAtLeast(0f)
}

@Composable
private fun SlockAppShellContent() {
    var selectedTab by remember { mutableStateOf("home") }
    val bottomSafeArea = bottomSafeAreaPadding()
    Column(modifier = Modifier.fillMaxSize().background(SlockColor.SurfaceWhite)) {
        Column(modifier = Modifier.weight(1f).fillMaxWidth()) {
            when (selectedTab) {
                "settings" -> SettingsHomeContent(settingsTabBarSmokePayload.copy(subtitle = "Shared settings"), onSelect = {})
                "tasks" -> AppShellPlaceholderContent(
                    title = "Tasks",
                    subtitle = "Shared task surface will mount here",
                    iconName = "square-check-big"
                )
                "members" -> AppShellPlaceholderContent(
                    title = "Members",
                    subtitle = "Shared members surface will mount here",
                    iconName = "users"
                )
                else -> HomeComponentsSmokeContent()
            }
        }
        SlockBottomTabBar(
            items = appShellBottomTabs(selectedTab),
            onSelect = { selectedTab = it },
            modifier = Modifier.fillMaxWidth()
        )
        Spacer(modifier = Modifier.height((bottomSafeArea + 4f).dp))
    }
}


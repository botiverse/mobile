const val SETTINGS_STORAGE_PAGE = "compose_settings_storage"

@Page(SETTINGS_STORAGE_PAGE, supportInLocal = true)
internal class ComposeSettingsStoragePage : ai.slock.compose.base.BasePager() {
    override fun willInit() {
        super.willInit()
        setContent { SettingsStorageScreen() }
    }
}

@Serializable
internal data class KuiklySettingsStoragePayload(
    val instanceId: String = "",
    val totalTitle: String = "Storage used",
    val totalSize: String = "0 B",
    val refreshLabel: String = "Refresh",
    val safeClearNote: String = "Clearing cache never removes your account or server data.",
    val feedback: String = "",
    val rows: List<KuiklySettingsStorageRow> = emptyList()
)

@Serializable
internal data class KuiklySettingsStorageRow(
    val target: String = "",
    val iconName: String = "archive",
    val title: String = "",
    val detail: String = "",
    val size: String = "0 B",
    val clearLabel: String = "",
    val clearEnabled: Boolean = false,
    val clearInProgress: Boolean = false
)

private val settingsStorageSmokePayload = KuiklySettingsStoragePayload(
    instanceId = "settings-storage-smoke",
    totalSize = "22.5 MB",
    rows = listOf(
        KuiklySettingsStorageRow(
            target = "database",
            iconName = "archive",
            title = "Local database",
            detail = "Messages, task metadata, and server snapshots stored on this device.",
            size = "4.6 MB"
        ),
        KuiklySettingsStorageRow(
            target = "imageCache",
            iconName = "image",
            title = "Image cache",
            detail = "Downloaded image previews kept for faster viewing.",
            size = "17.4 MB",
            clearLabel = "Clear image cache",
            clearEnabled = true
        ),
        KuiklySettingsStorageRow(
            target = "temporaryAndLogs",
            iconName = "file-text",
            title = "Temporary files and logs",
            detail = "Debug logs and temporary files generated by the app.",
            size = "512 KB",
            clearLabel = "Clear temp files and logs",
            clearEnabled = true
        )
    )
)

@Composable
private fun SettingsStorageScreen() {
    val pager = LocalActivity.current.getPager() as Pager
    val bridge = Utils.bridgeModule(pager.pagerId)
    val payload = rememberStoragePayload(
        pager.pageData.params.optString("payload"),
        pager.pageData.params.optString("instanceId")
    )
    LaunchedEffect(payload) {
        bridge.log("settings_storage_render instanceId=${payload.instanceId} rows=${payload.rows.size}")
    }
    SettingsStorageContent(payload) { action, target ->
        bridge.settingsEvent(payload.instanceId, action, target)
    }
}

@Composable
private fun rememberStoragePayload(payload: String, instanceId: String): KuiklySettingsStoragePayload =
    remember(payload, instanceId) {
        runCatching {
            Json { ignoreUnknownKeys = true }
                .decodeFromString(KuiklySettingsStoragePayload.serializer(), payload)
                .let { if (it.instanceId.isBlank()) it.copy(instanceId = instanceId) else it }
        }.getOrElse { settingsStorageSmokePayload.copy(instanceId = instanceId) }
    }

@Composable
internal fun SettingsStorageContent(
    payload: KuiklySettingsStoragePayload,
    onEvent: (String, String?) -> Unit
) {
    LazyColumn(
        modifier = Modifier.fillMaxSize().background(SlockColor.SurfaceWhite).padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        item {
            SettingsStorageSummary(
                title = payload.totalTitle,
                size = payload.totalSize,
                refreshLabel = payload.refreshLabel,
                onRefresh = { onEvent("refreshStorage", null) }
            )
        }
        payload.rows.forEach { row ->
            item {
                SettingsStorageRow(row) {
                    onEvent("clearStorage", row.target)
                }
            }
        }
        item {
            Text(
                payload.safeClearNote,
                style = SlockType.Caption.copy(color = SlockColor.TextMutedGray),
                color = SlockColor.TextMutedGray
            )
        }
        payload.feedback.takeIf { it.isNotBlank() }?.let { feedback ->
            item { SettingsStorageFeedback(feedback) }
        }
    }
}

@Composable
private fun SettingsStorageSummary(
    title: String,
    size: String,
    refreshLabel: String,
    onRefresh: () -> Unit
) {
    Column(
        modifier = Modifier.fillMaxWidth().background(SlockColor.BrandYellow).border(SlockStroke.Default, SlockColor.BorderBlack).padding(14.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        Text(title.uppercase(), style = SlockType.SectionLabel.copy(color = SlockColor.TextBlack), color = SlockColor.TextBlack)
        Text(size, style = SlockType.PageTitle.copy(color = SlockColor.TextBlack), color = SlockColor.TextBlack)
        SettingsStorageButton(refreshLabel, iconName = "refresh-cw", enabled = true, loading = false, onClick = onRefresh)
    }
}

@Composable
private fun SettingsStorageRow(row: KuiklySettingsStorageRow, onClear: () -> Unit) {
    Column(
        modifier = Modifier.fillMaxWidth().background(SlockColor.SurfaceWhite).border(SlockStroke.Default, SlockColor.BorderBlack).padding(14.dp),
        verticalArrangement = Arrangement.spacedBy(10.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            IconBox(row.iconName)
            Column(modifier = Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(2.dp)) {
                Text(row.title, style = SlockType.Body.copy(color = SlockColor.TextBlack), color = SlockColor.TextBlack, maxLines = 1, overflow = TextOverflow.Ellipsis)
                Text(row.detail, style = SlockType.Caption.copy(color = SlockColor.TextMutedGray), color = SlockColor.TextMutedGray)
            }
            Text(row.size, style = SlockType.Body.copy(color = SlockColor.TextBlack), color = SlockColor.TextBlack, maxLines = 1, overflow = TextOverflow.Ellipsis)
        }
        if (row.clearLabel.isNotBlank()) {
            SettingsStorageButton(
                text = row.clearLabel,
                iconName = "trash",
                enabled = row.clearEnabled,
                loading = row.clearInProgress,
                onClick = onClear
            )
        }
    }
}

@Composable
private fun SettingsStorageButton(
    text: String,
    iconName: String,
    enabled: Boolean,
    loading: Boolean,
    onClick: () -> Unit
) {
    Button(
        onClick = if (enabled && !loading) onClick else ({}),
        enabled = enabled && !loading,
        modifier = Modifier.fillMaxWidth()
            .height(44.dp)
            .background(if (enabled && !loading) SlockColor.SurfaceWhite else SlockColor.EmptyStateGray)
            .border(SlockStroke.Default, SlockColor.BorderBlack)
            .padding(horizontal = 12.dp)
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            SlockLucideIcon(iconName, modifier = Modifier.size(16.dp))
            Text(
                if (loading) "$text..." else text,
                style = SlockType.Button.copy(color = SlockColor.TextBlack),
                color = SlockColor.TextBlack,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis,
                modifier = Modifier.weight(1f)
            )
        }
    }
}

@Composable
private fun SettingsStorageFeedback(text: String) {
    Text(
        text,
        style = SlockType.Body.copy(color = SlockColor.TextBlack),
        color = SlockColor.TextBlack,
        modifier = Modifier.fillMaxWidth().background(SlockColor.AccentCyan).border(SlockStroke.Default, SlockColor.BorderBlack).padding(14.dp)
    )
}

@Composable
private fun IconBox(iconName: String) {
    Box(
        modifier = Modifier.size(42.dp).background(SlockColor.EmptyStateGray).border(SlockStroke.Default, SlockColor.BorderBlack),
        contentAlignment = Alignment.Center
    ) {
        SlockLucideIcon(iconName, modifier = Modifier.size(22.dp))
    }
}

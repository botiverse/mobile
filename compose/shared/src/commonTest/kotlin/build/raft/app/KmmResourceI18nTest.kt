/**
 * Smoke tests for the Compose resources wiring of the shared string catalogs
 * (formerly the KuiklyBase KmmResource plugin; the test name is kept).
 *
 * These tests do **not** exercise the locale-resolved runtime string lookup
 * (RaftStringDescResolutionTest does). They prove the generator picked up
 * the `composeResources` values catalogs and exposed the keys as
 * `StringResource` handles in the generated `Res`.
 *
 * The 2 cases:
 *   1. `common_ok` — short literal, used by many confirm/dismiss surfaces.
 *   2. `common_cancel` — short literal, the most common action button label.
 *
 * Together they guarantee:
 *   - The plugin is on the classpath and the generator task runs.
 *   - Both `base/` (en) and `zh-rCN/` (Simplified Chinese) XML files are parsed
 *     without build errors.
 *   - The generated `Res.string.<key>` references resolve in commonMain tests.
 */
class KmmResourceI18nTest {


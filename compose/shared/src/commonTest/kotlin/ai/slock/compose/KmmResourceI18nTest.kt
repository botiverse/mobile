package ai.slock.compose

import ai.slock.compose.resources.MR
import com.tencent.tmm.kmmresource.resource.desc.RawStringDesc
import com.tencent.tmm.kmmresource.resource.desc.ResourceFormattedStringDesc
import com.tencent.tmm.kmmresource.resource.desc.ResourceStringDesc
import com.tencent.tmm.kmmresource.resource.desc.StringDesc
import com.tencent.tmm.kmmresource.resource.desc.desc
import com.tencent.tmm.kmmresource.resource.format
import kotlin.test.Test
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

/**
 * Smoke tests for the KuiklyBase KmmResource plugin wiring in the shared module.
 *
 * These tests do **not** exercise the locale-resolved runtime string lookup
 * (which needs a platform Context / Localize). They prove the generator picked
 * up our `resources/MR/base/strings.xml` and `resources/MR/zh-rCN/strings.xml`
 * and exposed the new keys as `StringResource` handles in the generated `MR`.
 *
 * The 2 cases:
 *   1. `common_ok` — short literal, used by many confirm/dismiss surfaces.
 *   2. `common_cancel` — short literal, the most common action button label.
 *
 * Together they guarantee:
 *   - The plugin is on the classpath and the generator task runs.
 *   - Both `base/` (en) and `zh-rCN/` (Simplified Chinese) XML files are parsed
 *     without build errors.
 *   - The generated `MR.strings.<key>` references resolve in commonMain tests.
 */
class KmmResourceI18nTest {

    @Test
    fun commonOkStringResourceIsGenerated() {
        val resource = MR.strings.common_ok
        assertNotNull(resource, "MR.strings.common_ok must be generated by the KmmResource plugin")
        val desc: StringDesc = resource.desc()
        assertTrue(
            desc is ResourceStringDesc,
            "MR.strings.common_ok.desc() must produce a ResourceStringDesc"
        )
    }

    @Test
    fun commonCancelStringResourceIsGenerated() {
        val resource = MR.strings.common_cancel
        assertNotNull(resource, "MR.strings.common_cancel must be generated by the KmmResource plugin")
        val desc: StringDesc = resource.desc()
        assertTrue(
            desc is ResourceStringDesc,
            "MR.strings.common_cancel.desc() must produce a ResourceStringDesc"
        )
    }

    @Test
    fun bottomTabStringResourcesAreGenerated() {
        val tabResources = listOf(
            MR.strings.tab_home,
            MR.strings.tab_tasks,
            MR.strings.tab_members,
            MR.strings.tab_settings
        )

        tabResources.forEach { resource ->
            val desc: StringDesc = resource.desc()
            assertTrue(
                desc is ResourceStringDesc,
                "bottom tab resources must produce ResourceStringDesc entries"
            )
        }
    }

    @Test
    fun threadComposerActionStringResourcesAreGenerated() {
        val desc: StringDesc = MR.strings.thread_composer_insert_newline.desc()
        assertTrue(
            desc is ResourceStringDesc,
            "thread composer newline action must use KMM Resource strings"
        )
    }

    @Test
    fun commonOkAndCancelAreDistinctGeneratedEntries() {
        // Both keys exist independently; this catches a regression where the
        // generator accidentally collapses/aliases two distinct <string> entries.
        val okResource = MR.strings.common_ok
        val cancelResource = MR.strings.common_cancel
        assertNotNull(okResource)
        assertNotNull(cancelResource)
        val okDesc: StringDesc = okResource.desc()
        val cancelDesc: StringDesc = cancelResource.desc()
        assertTrue(
            okDesc is ResourceStringDesc && cancelDesc is ResourceStringDesc,
            "ok and cancel descs must both be ResourceStringDescs"
        )
        // Distinct identity proves the generator didn't alias both names to
        // the same generated entry. (We intentionally don't reach into
        // ResourceStringDesc.stringRes here — that property is private in
        // the Android-actual data class and only commonMain treats it as
        // public; the type check above is enough to fail compilation if
        // the generator stops emitting distinct keys.)
        assertTrue(
            okDesc != cancelDesc,
            "ok and cancel descs must be distinct instances"
        )
    }

    @Test
    fun formattedStringResourceBuildsViaCommonExtension() {
        // `format()` lives in commonMain (resource-core), and its
        // presence proves the runtime extension is on the test classpath.
        val formatted: StringDesc = MR.strings.common_ok.format(listOf("ignored-arg"))
        assertNotNull(formatted)
        assertTrue(
            formatted is ResourceFormattedStringDesc,
            "format() must produce a ResourceFormattedStringDesc"
        )
    }

    @Test
    fun rawStringDescIsUsableForLiterals() {
        // Bonus: verify the common `String.desc()` extension (the literal helper)
        // also resolves, so the test file is itself a sanity check on the API
        // surface we expect to consume from shared code.
        val raw: StringDesc = "raw".desc()
        assertNotNull(raw)
        assertTrue(raw is RawStringDesc, "raw literal desc must be a RawStringDesc")
    }
}

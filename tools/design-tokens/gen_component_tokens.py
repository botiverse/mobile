#!/usr/bin/env python3
"""Generate the mobile component tokens from raft-ui's tokens.resolved.json.

raft-ui (0.102.23 and later) ships every numeric token of tokens.json resolved to a plain number
in four contexts, so a reader that can't evaluate CSS gets the same values the Web computes:

  touch      a phone (the token's own value)
  fine       a mouse or a trackpad at any width (`@media (pointer: fine)`)
  desktop    from 768px with a mouse or a trackpad (`@media (width >= 48rem) and (pointer: fine)`)
  wideTouch  from 768px by touch, a tablet (`@media (width >= 48rem) and (pointer: coarse)`;
             raft-ui 0.103.4, raft-design #1416: the 48 head, 36 bar buttons, 20 bar icons)

These are the sizes the Web and the apps both draw (design/foundations/tokens.md, component
tokens): control and row heights, heads, bars, the list toolbar, the tab bar. Writes
compose/designsystem/.../tokens/RaftUiComponentTokens.g.kt: a dimension in dp (a font size and a
line height in sp), a duration in ms, a font weight and a number as they are.

The file is also checked against the stylesheets (gen_dimensions.py parses the same pinned
foundation.css): every token the CSS resolves must give the same value in each context, so the two
generated files can't disagree.

  python3 tools/design-tokens/gen_component_tokens.py          # regenerate
  python3 tools/design-tokens/gen_component_tokens.py --check  # CI: the Kotlin file is current
"""
import json, sys
from pathlib import Path

import gen_dimensions

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = ROOT / "compose/designsystem/src/commonMain/kotlin/build/raft/designsystem/tokens/RaftUiComponentTokens.g.kt"
CONTEXTS = ("touch", "fine", "desktop", "wideTouch")
# gen_dimensions' contexts (the App's: a phone, a wide window by touch, a wide window with a mouse)
# against the file's.
CSS_CONTEXTS = {"compact": "touch", "wide": "wideTouch", "fine": "desktop"}
TEXT_LENGTHS = ("font-size", "line-height")


def tokens(tree, path=()):
    for key, node in tree.items():
        if key.startswith("$") or not isinstance(node, dict):
            continue
        if "$value" in node:
            yield "-".join(path + (key,)), node["$type"], node["$value"]
        else:
            yield from tokens(node, path + (key,))


def camel(name):
    parts = name.split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def kotlin(name, kind, value):
    """(Kotlin type, literal) for one value."""
    if kind == "dimension":
        number = str(int(value)) if value == int(value) else repr(float(value))
        if name.endswith(TEXT_LENGTHS):
            return "TextUnit", f"{number}.sp"
        return "Dp", f"{number}.dp"
    if kind in ("fontWeight", "duration"):
        if value != int(value):
            raise SystemExit(f"{name}: a {kind} must be whole, got {value}")
        return "Int", str(int(value))
    if kind == "number":
        return "Float", f"{float(value)!r}f"
    raise SystemExit(f"{name}: unknown token type {kind!r}")


def generate():
    manifest = json.loads((HERE / "manifest.json").read_text())
    source = manifest["sources"]["raftUiResolvedTokens"]
    tree = json.loads((HERE / source["path"]).read_text())
    rows = sorted(tokens(tree))
    for name, kind, value in rows:
        if set(value) != set(CONTEXTS):
            raise SystemExit(f"{name}: expected contexts {CONTEXTS}, got {sorted(value)}")

    # Cross-check with the stylesheets.
    css, _, _ = gen_dimensions.compute()
    mismatches = []
    for name, kind, value in rows:
        if kind != "dimension":
            continue
        for css_context, context in CSS_CONTEXTS.items():
            got = css[css_context].get(f"--{name}")
            if got is not None and got != value[context]:
                mismatches.append(f"--{name}: foundation.css {css_context} {got}, tokens.resolved.json {context} {value[context]}")
    if mismatches:
        raise SystemExit("tokens.resolved.json disagrees with the stylesheets:\n  " + "\n  ".join(mismatches))

    def kdoc(name, kind, value):
        unit = {"dimension": "px", "duration": "ms"}.get(kind, "")
        shown = " / ".join(f"{c} {value[c]:g}{unit}" for c in CONTEXTS)
        return f"        /** `{name}`: {shown}. */"

    def block(context):
        lines = []
        for name, kind, value in rows:
            ktype, literal = kotlin(name, kind, value[context])
            lines.append(f"        override val {camel(name)}: {ktype} = {literal}")
        return "\n".join(lines)

    abstract = "\n".join(
        f"{kdoc(n, k, v)}\n        abstract val {camel(n)}: {kotlin(n, k, v['touch'])[0]}" for n, k, v in rows
    )
    kt = f"""// GENERATED by tools/design-tokens/gen_component_tokens.py — do not edit.
// Source (tools/design-tokens/manifest.json): {source['origin']} sha256={source['sha256'][:16]}
package build.raft.designsystem.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/**
 * raft-ui's component tokens, the sizes the Web and the apps both draw, from its
 * `tokens.resolved.json`, in the four contexts the Web resolves them for: [Touch] a phone, [Fine] a
 * mouse or a trackpad in a narrow window, [Desktop] a wide window with a mouse or a trackpad,
 * [WideTouch] a wide window by touch, a tablet ([of]). A dimension is in dp (a font size and a line height
 * in sp), a duration in ms. Names are the token's path, camel-cased (`list-toolbar.height` is
 * [Values.listToolbarHeight]).
 */
object RaftUiComponentTokens {{
    sealed class Values {{
{abstract}
    }}

    data object Touch : Values() {{
{block("touch")}
    }}

    data object Fine : Values() {{
{block("fine")}
    }}

    data object Desktop : Values() {{
{block("desktop")}
    }}

    data object WideTouch : Values() {{
{block("wideTouch")}
    }}

    /**
     * The values for a window that is [wide] or not, used with a mouse or trackpad ([fine]) or a
     * finger. The Web's desktop starts at 768px; the app's wide layout at its own breakpoint.
     */
    fun of(wide: Boolean, fine: Boolean): Values =
        when {{
            fine && wide -> Desktop
            fine -> Fine
            wide -> WideTouch
            else -> Touch
        }}
}}
"""
    return kt, len(rows)


def main():
    kt, n = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != kt:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/design-tokens/gen_component_tokens.py")
        print(f"component tokens up to date ({n} tokens x {len(CONTEXTS)} contexts)")
        return
    OUT.write_text(kt)
    print(f"wrote {OUT.relative_to(ROOT)} ({n} tokens x {len(CONTEXTS)} contexts)")


if __name__ == "__main__":
    main()

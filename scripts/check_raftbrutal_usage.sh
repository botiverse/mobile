#!/usr/bin/env bash
# The legacy "Brutal" UI layer (RaftBrutal* composables and their option / item / tone types,
# compose/shared/.../app/components/RaftBrutal*.kt, BrutalListRow.kt, RaftBrutalDropdownMenu.kt)
# and the brutal accent tokens RaftColor.BrandYellow / AccentPink / AccentCyan are deprecated in
# favour of compose/designsystem (see docs/raftbrutal-migration.md). Kotlin only warns on a
# deprecated use, so this check is the gate: per file, the number of uses may not grow beyond
# the checked-in baseline (scripts/raftbrutal_usage_baseline.tsv). A file not in the baseline
# may have none. Migrating a file lowers its count; re-record the baseline with
# --update-baseline so the lower count becomes the new ceiling.
#
# A use is one `RaftBrutal<Name>` identifier or one `RaftColor.BrandYellow|AccentPink|AccentCyan`
# outside import lines and comment lines, in any .kt / .kts file under compose/*/src.
set -euo pipefail

baseline_rel="scripts/raftbrutal_usage_baseline.tsv"

usage() {
  cat <<'EOF'
Usage: scripts/check_raftbrutal_usage.sh [--root <path>] [--update-baseline] [--self-test]
EOF
}

# scan <root> <baseline relative to root> <mode: check|update>
# check: 0 = no file grew, 1 = growth (printed). update: rewrites the baseline.
scan() {
  python3 - "$1" "$2" "$3" <<'PY'
import os, re, sys

root, baseline_rel, mode = sys.argv[1], sys.argv[2], sys.argv[3]
baseline_path = os.path.join(root, baseline_rel)
brutal = re.compile(r"\bRaftBrutal\w*")
tokens = re.compile(r"\bRaftColor\.(BrandYellow|AccentPink|AccentCyan)\b")
skip_dirs = {"build", ".gradle", ".git", "node_modules"}

def code_part(line):
    s = line.strip()
    if s.startswith(("import ", "//", "*", "/*")):
        return ""
    # Drop a trailing line comment (`//` after whitespace, so URLs in strings survive).
    return re.split(r"\s//", line, maxsplit=1)[0]

counts = {}
compose_root = os.path.join(root, "compose")
for dirpath, dirs, files in os.walk(compose_root):
    parts = os.path.relpath(dirpath, compose_root).split(os.sep)
    in_src = "src" in parts
    # `build` is Gradle output next to src/, but also the package root under src/.
    dirs[:] = [d for d in dirs if d not in skip_dirs or (d == "build" and in_src)]
    if not in_src:
        continue
    for name in files:
        if not name.endswith((".kt", ".kts")):
            continue
        path = os.path.join(dirpath, name)
        rel = os.path.relpath(path, root).replace(os.sep, "/")
        b = t = 0
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                code = code_part(line)
                if code:
                    b += len(brutal.findall(code))
                    t += len(tokens.findall(code))
        if b or t:
            counts[rel] = (b, t)

if mode == "update":
    with open(baseline_path, "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/check_raftbrutal_usage.sh --update-baseline. Do not raise a count by hand.\n")
        fh.write("# path\tRaftBrutal* uses\tRaftColor.BrandYellow/AccentPink/AccentCyan uses\n")
        for rel in sorted(counts):
            b, t = counts[rel]
            fh.write(f"{rel}\t{b}\t{t}\n")
    print(f"wrote {baseline_rel}: {len(counts)} files, {sum(c[0] for c in counts.values())} RaftBrutal* uses, "
          f"{sum(c[1] for c in counts.values())} legacy token uses")
    sys.exit(0)

baseline = {}
if os.path.exists(baseline_path):
    with open(baseline_path, encoding="utf-8") as fh:
        for line in fh:
            if not line.strip() or line.startswith("#"):
                continue
            rel, b, t = line.rstrip("\n").split("\t")
            baseline[rel] = (int(b), int(t))

grew = []
shrank = []
for rel, (b, t) in sorted(counts.items()):
    bb, bt = baseline.get(rel, (0, 0))
    if b > bb:
        grew.append((rel, "RaftBrutal* components", b, bb, "use the build.raft.designsystem component listed in docs/raftbrutal-migration.md"))
    if t > bt:
        grew.append((rel, "RaftColor.BrandYellow/AccentPink/AccentCyan", t, bt, "use RaftColor.Brand/Frame/BrandSoft, Attention/AttentionSoft or Info/InfoSoft"))
    if b < bb or t < bt:
        shrank.append(rel)
for rel in baseline:
    if rel not in counts:
        shrank.append(rel)
for rel, what, now, allowed, fix in grew:
    print(f"::error file={rel}::{what}: {now} uses, baseline allows {allowed}. Deprecated legacy UI; {fix}.", file=sys.stderr)
if shrank:
    print(f"note: {len(shrank)} file(s) dropped below the baseline; run scripts/check_raftbrutal_usage.sh --update-baseline to lock in the lower counts.")
sys.exit(1 if grew else 0)
PY
}

self_test() {
  local tmp
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' RETURN
  local app="$tmp/compose/shared/src/commonMain/kotlin/build/raft/app"
  mkdir -p "$app" "$tmp/scripts" "$tmp/compose/shared/build/generated"
  printf 'import build.raft.app.components.RaftBrutalActionButton\nfun a() {\n    RaftBrutalActionButton(text = "x") // RaftBrutalIconButton\n    val c = RaftColor.BrandYellow\n}\n' > "$app/Page.kt"
  printf '// RaftBrutalCard in a comment\n * RaftColor.AccentPink in KDoc\nval url = "https://raft.build/a" // RaftBrutalCard note\n' > "$app/Clean.kt"
  printf 'RaftBrutalCard()\n' > "$tmp/compose/shared/build/generated/Ignored.kt"
  scan "$tmp" "$baseline_rel" update >/dev/null
  grep -q $'compose/shared/src/commonMain/kotlin/build/raft/app/Page.kt\t1\t1' "$tmp/$baseline_rel" \
    || { echo "self-test: unexpected baseline:" >&2; cat "$tmp/$baseline_rel" >&2; return 1; }
  if grep -q 'Clean.kt\|Ignored.kt' "$tmp/$baseline_rel"; then
    echo "self-test: counted a comment, URL or build output" >&2; return 1
  fi
  scan "$tmp" "$baseline_rel" check >/dev/null 2>&1 || { echo "self-test: baseline tree failed" >&2; return 1; }

  local bad
  for bad in \
    'fun b() { RaftBrutalIconButton(onClick = {}) }' \
    'val t = RaftColor.AccentCyan' \
    'val o = listOf(RaftBrutalSelectOption("a", "A"))'; do
    printf '%s\n' "$bad" >> "$app/Page.kt"
    if scan "$tmp" "$baseline_rel" check >/dev/null 2>&1; then
      echo "self-test: missed growth: $bad" >&2; return 1
    fi
    scan "$tmp" "$baseline_rel" update >/dev/null
  done
  printf 'fun n() { RaftBrutalCard() }\n' > "$app/NewPage.kt"
  if scan "$tmp" "$baseline_rel" check >/dev/null 2>&1; then
    echo "self-test: missed a use in a file not in the baseline" >&2; return 1
  fi
  rm "$app/NewPage.kt"
  printf 'fun a() {}\n' > "$app/Page.kt"
  scan "$tmp" "$baseline_rel" check >/dev/null 2>&1 || { echo "self-test: a shrinking file failed" >&2; return 1; }
  echo "check_raftbrutal_usage self-test passed"
}

root="."
mode="check"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --root) root="$2"; shift 2 ;;
    --update-baseline) mode="update"; shift ;;
    --self-test) self_test; exit $? ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
done

if [[ "$root" == "." ]]; then
  root="$(cd "$(dirname "$0")/.." && pwd)"
fi
scan "$root" "$baseline_rel" "$mode"
if [[ "$mode" == "check" ]]; then
  echo "RaftBrutal usage: no file grew beyond $baseline_rel"
fi

#!/usr/bin/env python3
"""Generate the Thread Composer Hanzi -> pinyin lookup table."""

from __future__ import annotations

import argparse
import re
import sys
import unicodedata
import urllib.request
from pathlib import Path


PINYIN_DATA_COMMIT = "923b108dc5d45dee061324c011b478fb649f8b73"
PINYIN_DATA_URL = (
    "https://raw.githubusercontent.com/mozillazg/pinyin-data/"
    f"{PINYIN_DATA_COMMIT}/pinyin.txt"
)
OUTPUT_PATH = Path(
    "compose/shared/src/commonMain/kotlin/build/raft/app/ThreadComposerPinyinData.kt"
)
BASIC_START = 0x4E00
BASIC_END = 0x9FFF
PINYIN_ROW_RE = re.compile(r"^U\+([0-9A-Fa-f]+):\s*([^#]+)")
PINYIN_TONE_REPLACEMENTS = str.maketrans(
    {
        "ā": "a",
        "á": "a",
        "ǎ": "a",
        "à": "a",
        "ē": "e",
        "é": "e",
        "ě": "e",
        "è": "e",
        "ê": "e",
        "ī": "i",
        "í": "i",
        "ǐ": "i",
        "ì": "i",
        "ō": "o",
        "ó": "o",
        "ǒ": "o",
        "ò": "o",
        "ū": "u",
        "ú": "u",
        "ǔ": "u",
        "ù": "u",
        "ǖ": "v",
        "ǘ": "v",
        "ǚ": "v",
        "ǜ": "v",
        "ü": "v",
        "ń": "n",
        "ň": "n",
        "ǹ": "n",
        "ḿ": "m",
    }
)


def normalize_pinyin(value: str) -> str:
    translated = value.strip().lower().translate(PINYIN_TONE_REPLACEMENTS)
    decomposed = unicodedata.normalize("NFKD", translated)
    without_marks = "".join(
        char for char in decomposed if unicodedata.category(char) != "Mn"
    )
    return "".join(char for char in without_marks if "a" <= char <= "z")


def read_source(source: str) -> str:
    if source.startswith("http://") or source.startswith("https://"):
        with urllib.request.urlopen(source) as response:
            return response.read().decode("utf-8")
    return Path(source).read_text(encoding="utf-8")


def parse_basic_pinyin(source_text: str) -> list[str]:
    values = [""] * (BASIC_END - BASIC_START + 1)
    for line in source_text.splitlines():
        match = PINYIN_ROW_RE.match(line.strip())
        if not match:
            continue
        codepoint = int(match.group(1), 16)
        if codepoint < BASIC_START or codepoint > BASIC_END:
            continue
        first_reading = match.group(2).split(",", maxsplit=1)[0]
        values[codepoint - BASIC_START] = normalize_pinyin(first_reading)
    return values


def quote_kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_syllables(syllables: list[str]) -> list[str]:
    lines = ["private val ThreadComposerPinyinSyllables: Array<String> =", "    arrayOf("]
    for index in range(0, len(syllables), 8):
        chunk = syllables[index : index + 8]
        suffix = "," if index + 8 < len(syllables) else ""
        lines.append("        " + ", ".join(quote_kotlin_string(item) for item in chunk) + suffix)
    lines.append("    )")
    return lines


def render_indexes(indexes: list[int]) -> list[str]:
    chunks = []
    for index in range(0, len(indexes), 32):
        chunk = indexes[index : index + 32]
        chunks.append("".join(f"\\u{item:04x}" for item in chunk))
    lines = ["private val ThreadComposerPinyinBasicIndexes: String ="]
    for index, chunk in enumerate(chunks):
        suffix = " +" if index + 1 < len(chunks) else ""
        indent = "    " if index == 0 else "        "
        lines.append(f'{indent}"{chunk}"{suffix}')
    return lines


def render_kotlin(values: list[str]) -> str:
    syllables = [""] + sorted({value for value in values if value})
    syllable_indexes = {value: index for index, value in enumerate(syllables)}
    indexes = [syllable_indexes[value] for value in values]
    lines = [
        "package build.raft.app",
        "",
        "// Generated by scripts/generate_thread_composer_pinyin_data.py.",
        "// Data source: mozillazg/pinyin-data pinyin.txt",
        f"// Source commit: {PINYIN_DATA_COMMIT}",
        "// Source URL: https://github.com/mozillazg/pinyin-data",
        "// Source license: MIT, Copyright (c) 2016 mozillazg.",
        "// Range: CJK Unified Ideographs U+4E00..U+9FFF.",
        "// Values are the first reading per pinyin-data row, tone-stripped and lowercase.",
        "",
        "private const val ThreadComposerPinyinBasicStart = 0x4E00",
        "private const val ThreadComposerPinyinBasicEnd = 0x9FFF",
        "",
        *render_syllables(syllables),
        "",
        *render_indexes(indexes),
        "",
        "internal fun threadComposerGeneratedPinyin(char: Char): String? {",
        "    val code = char.code",
        "    if (code < ThreadComposerPinyinBasicStart || code > ThreadComposerPinyinBasicEnd) return null",
        "    val index = ThreadComposerPinyinBasicIndexes[code - ThreadComposerPinyinBasicStart].code",
        "    return ThreadComposerPinyinSyllables.getOrNull(index)?.takeIf { it.isNotEmpty() }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=PINYIN_DATA_URL)
    parser.add_argument("--output", default=str(OUTPUT_PATH))
    args = parser.parse_args()

    source_text = read_source(args.source)
    values = parse_basic_pinyin(source_text)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_kotlin(values), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

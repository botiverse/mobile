def pascal_name(name):
    return "".join(part.capitalize() for part in name.split("-"))


def download_svg(name, version):
    url = f"https://raw.githubusercontent.com/lucide-icons/lucide/{version}/icons/{name}.svg"
    for attempt in range(3):
        try:
            print(f"  ↓  {name}")
            req = urllib.request.Request(url, headers={"User-Agent": "slock-lucide-generator"})
            with urllib.request.urlopen(req, timeout=20) as resp:
                return resp.read().decode("utf-8").strip()
        except Exception:
            if attempt == 2:
                raise
            time.sleep(1 + attempt)


def run_s2c(svg_path, out_path, package):
    result = subprocess.run(
        [
            "s2c",
            "-o", out_path,
            "-p", package,
            "-t", f"{package}.LucideIcons",
            "--no-preview",
            "--minified",
            "-opt=false",
            "--kmp=false",
            svg_path,
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"s2c failed for {svg_path}:\n{result.stderr}")


def extract_builder_block(kt_content, prop):
    """
    From s2c output, extract the ImageVector.Builder(...)...build() expression.
    Returns a string already indented at 8 spaces (ready for `by lazy { }` body).
    """
    m_start = re.search(r"^\s*return (ImageVector\.Builder\()", kt_content, re.MULTILINE)
    if not m_start:
        raise ValueError(f"No ImageVector.Builder found for {prop}")

    m_end = re.search(r"(\.build\(\))\.also \{ \w+ = it \}", kt_content)
    if not m_end:
        raise ValueError(f"No .build().also found for {prop}")

    block = kt_content[m_start.start(1): m_end.end(1)]

    # Fix the icon name inside the builder
    block = re.sub(r'(name\s*=\s*")[^"]*(")', rf'\g<1>Lucide{prop}\2', block, count=1)

    return block


def collect_imports(kt_content):
    return [line for line in kt_content.splitlines() if line.startswith("import ")]


def generate(icons, version, output):
    package = "ai.slock.android.ui.icons"
    entries = []
    all_imports = set()

    with tempfile.TemporaryDirectory() as tmpdir:
        for name in icons:
            prop = pascal_name(name)
            svg = download_svg(name, version)

            svg_path = os.path.join(tmpdir, f"{name}.svg")
            with open(svg_path, "w", encoding="utf-8") as f:
                f.write(svg)

            out_path = os.path.join(tmpdir, f"{prop}.kt")
            run_s2c(svg_path, out_path, package)

            with open(out_path, "r", encoding="utf-8") as f:
                kt_content = f.read()

            all_imports.update(collect_imports(kt_content))
            builder_block = extract_builder_block(kt_content, prop)
            entries.append((prop, builder_block))

    sorted_imports = sorted(all_imports)

    lines = [
        f"package {package}",
        "",
        *sorted_imports,
        "",
        "// Generated by scripts/lucide_to_shared_icons.py. Do not edit by hand.",
        "object LucideIcons {",
        f'    const val Version: String = "{version}"',
        "",
    ]

    for prop, block in entries:
        # Indent the block 8 spaces inside `by lazy { }`
        indented = "\n".join(
            "        " + line if line.strip() else ""
            for line in block.splitlines()
        )
        lines += [
            f"    val {prop}: ImageVector by lazy {{",
            indented,
            "    }",
            "",
        ]

    all_props = ", ".join(prop for prop, _ in entries)
    lines += [
        f"    val All: List<ImageVector> = listOf({all_props})",
        "}",
        "",
    ]

    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"\nGenerated {len(entries)} icons -> {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("icons", nargs="*", help="Lucide icon names (default: Slock set)")
    parser.add_argument("--version", default=DEFAULT_VERSION)
    parser.add_argument(
        "--output",
        default=os.path.join(
            os.path.dirname(os.path.abspath(__file__)),
            "..",
            "app",
            "src",
            "main",
            "java",
            "ai",
            "slock",
            "android",
            "ui",
            "icons",
            "LucideIcons.kt",
        ),
    )
    args = parser.parse_args()
    generate(args.icons or DEFAULT_ICONS, args.version, os.path.abspath(args.output))


if __name__ == "__main__":
    main()

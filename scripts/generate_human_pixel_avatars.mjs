#!/usr/bin/env node
// Regenerates the human pixel-avatar art (people's built avatars,
// `pixel-human:v1:...`) from the vendored copy of slock's
// packages/shared/assets/humanAvatarLayers.json, the same art the web's
// HumanPixelAvatar and the Server's SVG route draw.
//
// Input:  compose/shared/src/androidUnitTest/resources/humanavatar/humanAvatarLayers.json
//         (byte-exact copy at the slock SHA pinned in
//         scripts/check_human_pixel_avatar_vector.sh, which verifies its digest)
// Output: compose/shared/src/commonMain/kotlin/build/raft/app/RaftHumanPixelAvatarArtData.kt
//
// To take new art: copy the JSON (and src/fixtures/humanAvatarDefault.png) from
// slock at the new commit, bump the SHA and digests in the check script, the
// port and its test, then run this script. --check fails when the committed
// Kotlin does not match the vendored JSON (no write).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = join(repoRoot, "compose/shared/src/androidUnitTest/resources/humanavatar/humanAvatarLayers.json");
const outputPath = join(repoRoot, "compose/shared/src/commonMain/kotlin/build/raft/app/RaftHumanPixelAvatarArtData.kt");

const bytes = readFileSync(inputPath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
const art = JSON.parse(bytes.toString("utf8"));

const fail = (message) => {
  throw new Error(`humanAvatarLayers.json: ${message}`);
};
if (!Number.isInteger(art.size) || art.size <= 0) fail("`size` must be a positive integer");
if (typeof art.artVersion !== "string") fail("`artVersion` must be a string");
for (const key of ["roleColors", "fixed"]) if (!art[key] || typeof art[key] !== "object") fail(`missing \`${key}\``);
for (const key of ["background", "skin", "hair"]) if (!art.palettes?.[key]) fail(`missing palettes.${key}`);
if (!Array.isArray(art.layers)) fail("missing `layers`");
for (const layer of art.layers) {
  if (!Array.isArray(layer.rows) || layer.rows.length !== art.size) fail(`${layer.layer}:${layer.option} needs ${art.size} rows`);
  for (const row of layer.rows) if (typeof row !== "string" || row.length !== art.size) fail(`${layer.layer}:${layer.option} row width`);
}

const str = (value) => JSON.stringify(value);
const char = (value) => {
  if (typeof value !== "string" || value.length !== 1) fail(`role ${str(value)} is not one character`);
  return `'${value}'`;
};
const stringMap = (record) =>
  `mapOf(${Object.entries(record).map(([key, value]) => `${str(key)} to ${str(value)}`).join(", ")})`;

const layerFunctions = art.layers.map((layer, index) => {
  const group = layer.group === undefined ? "null" : str(layer.group);
  const z = layer.z === undefined ? "null" : String(layer.z);
  return [
    `// ${layer.layer}:${layer.option}`,
    `private fun raftHumanPixelAvatarLayer${index}() = RaftHumanPixelAvatarArtLayer(`,
    `    layer = ${str(layer.layer)},`,
    `    option = ${str(layer.option)},`,
    `    group = ${group},`,
    `    z = ${z},`,
    `    rows = listOf(`,
    ...layer.rows.map((row) => `        ${str(row)},`),
    `    ),`,
    `)`,
  ].join("\n");
});

const output = `// GENERATED by scripts/generate_human_pixel_avatars.mjs from the vendored slock
// packages/shared/assets/humanAvatarLayers.json — do not edit.
// Regenerate: node scripts/generate_human_pixel_avatars.mjs
package build.raft.app

/** sha256 of the humanAvatarLayers.json this art was generated from. */
internal const val RAFT_HUMAN_PIXEL_AVATAR_ART_SHA256 = ${str(sha256)}

/** The human pixel-avatar art (art revision ${art.artVersion}), in the JSON's layer order. */
internal val RaftHumanPixelAvatarArtData: RaftHumanPixelAvatarArt by lazy {
    RaftHumanPixelAvatarArt(
        artVersion = ${str(art.artVersion)},
        size = ${art.size},
        roleColors = mapOf(${Object.entries(art.roleColors).map(([role, source]) => `${char(role)} to ${str(source)}`).join(", ")}),
        fixed = ${stringMap(art.fixed)},
        backgroundPalette = ${stringMap(art.palettes.background)},
        skinPalette = ${stringMap(art.palettes.skin)},
        hairPalette = ${stringMap(art.palettes.hair)},
        layers = listOf(${art.layers.map((_, index) => `raftHumanPixelAvatarLayer${index}()`).join(", ")}),
    )
}

${layerFunctions.join("\n\n")}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== output) {
    console.error(`${outputPath} is out of date; run node scripts/generate_human_pixel_avatars.mjs`);
    process.exit(1);
  }
  console.log(`Human pixel-avatar art is up to date (sha256 ${sha256}).`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath} (art ${art.artVersion}, sha256 ${sha256}).`);
}

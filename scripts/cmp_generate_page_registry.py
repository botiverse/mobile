#!/usr/bin/env python3
"""Generate the CMP page registry from the Kuikly-style `@Page("name")` page classes.

CMP big switch, Phase A. Kuikly registered pages with a KSP processor; on CMP the hosts render a
page name through `RaftPageRegistry` (compose/shared, package build.raft.app.compat.pager), which
reads the two generated maps written here:

  * src/commonMain/.../compat/pager/RaftProductPages.g.kt  - pages under commonMain
  * src/visualFixtures/.../compat/pager/RaftVisualFixturePages.g.kt - visual fixture pages (only
    compiled with -PslockVisualFixtures=true; src/visualFixturesOff holds the empty stand-in)

Page names stay exactly what `@Page` declares (string literal or a `const val` resolved here), so
openPage callers, deep links and visual cases are unchanged. Re-run after adding/removing a page:

    python3 scripts/cmp_generate_page_registry.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SHARED = REPO / "compose/shared/src"
OUT_PACKAGE = "build.raft.app.compat.pager"
OUT_DIR = "kotlin/build/raft/app/compat/pager"

PAGE = re.compile(
    r"@Page\(\s*(?P<name>\"[^\"]*\"|[A-Za-z_][A-Za-z0-9_.]*)[^)]*\)\s*(?:@[A-Za-z_]+(?:\([^)]*\))?\s*)*"
    r"(?:(?:internal|public|private|open|final)\s+)*class\s+(?P<cls>[A-Za-z_][A-Za-z0-9_]*)"
)
PACKAGE = re.compile(r"^package\s+([A-Za-z0-9_.]+)", re.M)
CONST = re.compile(r"\bconst\s+val\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*String\s*)?=\s*\"([^\"]*)\"")


def collect_constants(roots: list[Path]) -> dict[str, str]:
    constants: dict[str, str] = {}
    for root in roots:
        for path in root.rglob("*.kt"):
            for name, value in CONST.findall(path.read_text(encoding="utf-8")):
                constants.setdefault(name, value)
    return constants


def collect_pages(root: Path, constants: dict[str, str]) -> list[tuple[str, str]]:
    pages: list[tuple[str, str]] = []
    for path in sorted(root.rglob("*.kt")):
        text = path.read_text(encoding="utf-8")
        if "@Page(" not in text:
            continue
        package = PACKAGE.search(text)
        prefix = (package.group(1) + ".") if package else ""
        for match in PAGE.finditer(text):
            raw = match.group("name")
            if raw.startswith('"'):
                name = raw[1:-1]
            else:
                key = raw.split(".")[-1]
                if key not in constants:
                    raise SystemExit(f"{path}: cannot resolve page name constant {raw}")
                name = constants[key]
            pages.append((name, prefix + match.group("cls")))
    names = [name for name, _ in pages]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        raise SystemExit(f"duplicate page names under {root}: {dupes}")
    return sorted(pages)


def render(value_name: str, pages: list[tuple[str, str]], source: str) -> str:
    lines = [
        "// GENERATED by scripts/cmp_generate_page_registry.py from the @Page classes in",
        f"// {source}. Do not edit; re-run the script.",
        f"package {OUT_PACKAGE}",
        "",
        f"internal val {value_name}: Map<String, () -> Pager> =",
        "    mapOf(",
    ]
    for name, cls in pages:
        lines.append(f'        "{name}" to {{ {cls}() }},')
    lines += ["    )", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    constants = collect_constants([SHARED / "commonMain", SHARED / "visualFixtures", SHARED / "visualFixtureData"])
    outputs = {
        SHARED / "commonMain" / OUT_DIR / "RaftProductPages.g.kt": render(
            "raftProductPageFactories",
            collect_pages(SHARED / "commonMain", constants),
            "compose/shared/src/commonMain",
        ),
        SHARED / "visualFixtures" / OUT_DIR / "RaftVisualFixturePages.g.kt": render(
            "raftVisualFixturePageFactories",
            collect_pages(SHARED / "visualFixtures", constants),
            "compose/shared/src/visualFixtures",
        ),
    }
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    for path in stale:
        print(("stale: " if args.check else "wrote: ") + str(path.relative_to(REPO)))
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
